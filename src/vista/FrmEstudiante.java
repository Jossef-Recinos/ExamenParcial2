    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(new Object[]{
            "ID ESTUDIANTE", "CARNET", "PRIMER NOMBRE", "SEGUNDO NOMBRE", "APELLIDOS", "DIRECCION",
            "TELEFONO", "CARRERA", "FECHA NACIMIENTO", "FECHA INGRESO"
        }, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false; // se edita desde los campos, no en la tabla
            }
        };
        jtEstudiante.setModel(modeloTabla);
        jtEstudiante.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jtEstudiante.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                cargarFilaSeleccionada();
            }
        });
    } 
    private void registrarEventos() {
        btnBuscar.addActionListener(e -> buscar());
        btnActualizar.addActionListener(e -> actualizar());
        btnLimpiar.addActionListener(e -> limpiarCampos());
        btnRefrescar.addActionListener(e -> cargarEstudiantes());
    }
    
    public void cargarEstudiantes() {
        try {
            List<Estudiante> lista = controlador.obtenerEstudiantes();
            modeloTabla.setRowCount(0);
            for (Estudiante es : lista) {
                modeloTabla.addRow(new Object[]{
                    es.getIdEstudiante(),
                    es.getCarnet(),
                    es.getPrimerNombre(),
                    es.getSegundoNombre(),
                    es.getApellidos(),
                    es.getDireccion(),
                    es.getTelefono(),
                    es.getCarrera(),
                    es.getFechaNacimiento(),
                    es.getFechaIngreso()
                });
            }
        } catch (SQLException e) {
            errorBaseDatos("No se pudieron cargar los estudiantes.", e);
        }
    }

    private void insertar() {
        try {
            controlador.agregarEstudiante(
                    texto(txtIdEstudiante), texto(txtCarnet), texto(txtPrimerNombre), texto(txtSegundoNombre),
                    texto(txtApellidos), texto(txtDireccion), texto(txtTelefono), texto(txtCarrera),
                    texto(txtFechaNacimiento), texto(txtFechaIngreso));
            cargarEstudiantes();
            limpiarCampos();
            mensaje("Estudiante insertado correctamente.");
        } catch (IllegalArgumentException e) {
            advertencia(e.getMessage());
        } catch (SQLException e) {
            if ("23505".equals(e.getSQLState())) { // llave duplicada en PostgreSQL
                advertencia("Ya existe un estudiante con ese ID o con ese carnet.");
            } else {
                errorBaseDatos("No se pudo insertar el estudiante.", e);
            }
        }
    }

    private void buscar() {
        try {
            Estudiante es = controlador.buscarEstudiante(texto(txtIdEstudiante));
            if (es == null) {
                advertencia("No existe un estudiante con ese ID.");
            } else {
                mostrarEnCampos(es);
            }
        } catch (IllegalArgumentException e) {
            advertencia(e.getMessage());
        } catch (SQLException e) {
            errorBaseDatos("No se pudo buscar el estudiante.", e);
        }
    }

    private void actualizar() {
        try {
            boolean ok = controlador.actualizarEstudiante(
                    texto(txtIdEstudiante), texto(txtCarnet), texto(txtPrimerNombre), texto(txtSegundoNombre),
                    texto(txtApellidos), texto(txtDireccion), texto(txtTelefono), texto(txtCarrera),
                    texto(txtFechaNacimiento), texto(txtFechaIngreso));
            if (ok) {
                cargarEstudiantes();
                limpiarCampos();
                mensaje("Estudiante actualizado correctamente.");
            } else {
                advertencia("No existe un estudiante con ese ID. Usa Insertar para crearlo.");
            }
        } catch (IllegalArgumentException e) {
            advertencia(e.getMessage());
        } catch (SQLException e) {
            if ("23505".equals(e.getSQLState())) {
                advertencia("Ese carnet ya pertenece a otro estudiante.");
            } else {
                errorBaseDatos("No se pudo actualizar el estudiante.", e);
            }
        }
    }

    private void eliminar() {
        String id = texto(txtIdEstudiante);
        if (id.isEmpty()) {
            advertencia("Selecciona un estudiante en la tabla o escribe su ID.");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Seguro que deseas eliminar al estudiante con ID " + id + "?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            if (controlador.eliminarEstudiante(id)) {
                cargarEstudiantes();
                limpiarCampos();
                mensaje("Estudiante eliminado correctamente.");
            } else {
                advertencia("No existe un estudiante con ese ID.");
            }
        } catch (IllegalArgumentException e) {
            advertencia(e.getMessage());
        } catch (SQLException e) {
            errorBaseDatos("No se pudo eliminar el estudiante.", e);
        }
    }

    private void cargarFilaSeleccionada() {
        int fila = jtEstudiante.getSelectedRow();
        if (fila < 0) {
            return;
        }
        txtIdEstudiante.setText(valor(fila, 0));
        txtCarnet.setText(valor(fila, 1));
        txtPrimerNombre.setText(valor(fila, 2));
        txtSegundoNombre.setText(valor(fila, 3));
        txtApellidos.setText(valor(fila, 4));
        txtDireccion.setText(valor(fila, 5));
        txtTelefono.setText(valor(fila, 6));
        txtCarrera.setText(valor(fila, 7));
        txtFechaNacimiento.setText(valor(fila, 8));
        txtFechaIngreso.setText(valor(fila, 9));
        txtIdEstudiante.setEditable(false); // el ID no se cambia al actualizar
    }

    private void mostrarEnCampos(Estudiante es) {
        txtIdEstudiante.setText(String.valueOf(es.getIdEstudiante()));
        txtCarnet.setText(es.getCarnet());
        txtPrimerNombre.setText(es.getPrimerNombre());
        txtSegundoNombre.setText(es.getSegundoNombre());
        txtApellidos.setText(es.getApellidos());
        txtDireccion.setText(es.getDireccion());
        txtTelefono.setText(String.valueOf(es.getTelefono()));
        txtCarrera.setText(es.getCarrera());
        txtFechaNacimiento.setText(es.getFechaNacimiento());
        txtFechaIngreso.setText(es.getFechaIngreso());
        txtIdEstudiante.setEditable(false);
    }

    private void limpiarCampos() {
        JTextField[] campos = {
            txtIdEstudiante, txtCarnet, txtPrimerNombre, txtSegundoNombre, txtApellidos, txtDireccion,
            txtTelefono, txtCarrera,txtFechaNacimiento, txtFechaIngreso
        };
        for (JTextField campo : campos) {
            campo.setText("");
        }
        txtIdEstudiante.setEditable(true);
        jtEstudiante.clearSelection();
        txtIdEstudiante.requestFocus();
    } 
    
    private String texto(JTextField campo) {
        return campo.getText().trim();
    }

    private String valor(int fila, int columna) {
        Object v = modeloTabla.getValueAt(fila, columna);
        return v == null ? "" : v.toString();
    }

    private void mensaje(String texto) {
        JOptionPane.showMessageDialog(this, texto, "Listo", JOptionPane.INFORMATION_MESSAGE);
    }

    private void advertencia(String texto) {
        JOptionPane.showMessageDialog(this, texto, "Revisa los datos", JOptionPane.WARNING_MESSAGE);
    }

    private void errorBaseDatos(String texto, SQLException e) {
        JOptionPane.showMessageDialog(this,
                texto + "\n\nDetalle: " + e.getMessage()
                + "\n\nRevisa que PostgreSQL esté encendido y que los datos de conexion/Conexion.java sean correctos.",
                "Error de base de datos", JOptionPane.ERROR_MESSAGE);
    }

